'use strict';
const fs = require('fs');
const assert = require('assert');
const server = fs.readFileSync('src/messaging.js', 'utf8');
const ui = fs.readFileSync('public/ext-messaging.js', 'utf8');
const contracts = fs.readFileSync('src/contracts.js', 'utf8');
const routeStart = server.indexOf("r.post('/messaging/support/to-admin'");
assert(routeStart >= 0, 'support-to-admin route exists');
const route = server.slice(routeStart, server.indexOf("r.get('/messaging/alert-health'", routeStart));
assert(route.includes("req.user.role !== 'ADMIN'"), 'server restricts contact to local ADMIN role');
assert(route.includes('LOCAL_ADMIN_REQUIRED'), 'server returns stable authorization code');
assert(route.indexOf("req.user.role !== 'ADMIN'") < route.indexOf('loadContractForUser'), 'role denied before support contract checks');
assert(ui.includes("const localAdmin = !sa && ME?.role === 'ADMIN'"), 'UI only exposes contact button to local ADMIN');
assert(ui.includes('localAdmin && (state.status?.features?.support?.enabled'), 'contact button also respects contract feature flags');
assert(ui.includes('msgSupportToAdmin()'), 'authorized users retain contact action');
assert(route.includes("if (req.user.is_global) throw new HttpError(400"), 'platform account cannot use client endpoint');
assert(contracts.includes("r.post('/me/license/renewal-request'"), 'license renewal endpoint remains available');
assert(!route.includes("req.user.role !== 'ADMIN'.*license"), 'B5 does not add a role restriction to renewal route');
console.log('messaging-superadmin-contact-role-static: 9/9 passed');
