const fs = require('fs');
const assert = require('assert');
const maintenance = fs.readFileSync('src/maintenance.js', 'utf8');
const backup = fs.readFileSync('src/backup.js', 'utf8');
const admin = fs.readFileSync('src/admin.js', 'utf8');
const ui = fs.readFileSync('public/ext-p12.js', 'utf8');
const ux = fs.readFileSync('public/ext-ux-v2.js', 'utf8');
const msg = fs.readFileSync('public/ext-messaging.js', 'utf8');
let n = 0; const ok = (v, m) => { assert.ok(v, m); n++; };
ok(maintenance.includes("req.user?.is_global"), 'routes maintenance réservées au Super Admin');
ok(maintenance.includes("process.env.RESTORE_ENABLED !== '1'"), 'restauration désactivée par défaut');
ok(maintenance.includes('global_reset_enabled: false') && maintenance.includes('Réinitialisation globale suspendue par sécurité'), 'réinitialisation globale suspendue pour protéger les données opérationnelles clients');
ok(maintenance.includes("backup.runBackup('pre-restore')"), 'sauvegarde de sécurité avant restauration');
ok(!maintenance.includes("backup.runBackup('pre-global-reset')"), 'aucune sauvegarde/reset destructif ne démarre tant que le périmètre plateforme-only n’est pas sûr');
ok(maintenance.includes("'SUPPRIMER TOUTES LES DONNEES'"), 'confirmation destructive explicite');
ok(maintenance.includes("--single-transaction"), 'restauration transactionnelle');
ok(maintenance.includes('MAX_RESTORE_BYTES'), 'taille upload bornée');
ok(maintenance.includes('zlib.createGunzip()') && maintenance.includes('await validateGzipFile(tmp)'), 'validation gzip en flux avant remplacement');
ok(maintenance.includes('user_sessions SET revoked_at=now()'), 'sessions révoquées après restauration');
ok(backup.includes("process.env.BACKUP_EMAIL_ATTACH === '1'"), 'pièce jointe email optionnelle');
ok(backup.includes('BACKUP_EMAIL_ATTACH_MAX_MB'), 'limite de taille pièce jointe');
ok(backup.includes('attachment_sent'), 'statut pièce jointe remonté');
ok(admin.includes("features.can_customize_report_exports === true"), 'personnalisation couleur soumise au contrat');
ok(admin.includes("INSERT INTO client_report_preferences"), 'préférence enregistrée au niveau client');
ok(ui.includes('restoreBackupFile'), 'action restauration présente');
ok(ui.includes('resetGlobalData'), 'action réinitialisation présente');
ok(ux.includes('window.editFour') && ux.includes('window.payFour'), 'boutons modifier/régler fournisseur reliés à des fonctions');
ok(msg.includes('window.msgSupportOpen') && msg.includes('window.msgSupportToAdmin'), 'boutons support Super Admin et client reliés à des fonctions');
console.log(`Étape 21 sauvegardes/restauration : ${n}/${n} contrôles statiques réussis.`);
